"""
Gemini Judge - AI-powered hallucination detection and grounding verification.

Uses Gemini 3 to:
1. Verify claims are semantically supported by evidence
2. Detect subtle hallucinations that regex can't catch
3. Generate adversarial test cases
4. Provide explanations for failures

This is the "Hack B" component that makes evals a differentiator.
"""

import os
import json
from typing import Any, Dict, List, Optional, Tuple
from datetime import datetime

from pydantic import BaseModel, Field

# Import Gemini client from cache module
try:
    from coprocessor.cache.gemini_client import GeminiClient
except ImportError:
    GeminiClient = None


class ClaimVerification(BaseModel):
    """Result of verifying a single claim against evidence."""

    claim_text: str
    is_supported: bool
    confidence: float = Field(ge=0.0, le=1.0)
    supporting_evidence_ids: List[str] = Field(default_factory=list)
    explanation: str = ""
    issues: List[str] = Field(default_factory=list)


class GeminiJudgeResult(BaseModel):
    """Result of Gemini judge evaluation."""

    passed: bool
    total_claims: int = 0
    supported_claims: int = 0
    unsupported_claims: int = 0

    claim_verifications: List[ClaimVerification] = Field(default_factory=list)

    # Overall assessment
    overall_explanation: str = ""

    # Metrics
    support_rate: float = 0.0
    average_confidence: float = 0.0

    # Performance
    latency_ms: float = 0
    tokens_used: int = 0
    cached_tokens: int = 0

    # Errors
    errors: List[str] = Field(default_factory=list)


class AdversarialTestCase(BaseModel):
    """An adversarial test case generated by Gemini."""

    id: str
    name: str
    description: str
    expected_result: str  # "pass" or "fail"
    expected_error_type: Optional[str] = None
    memo: Dict[str, Any]
    evidence_pack: Dict[str, Any]
    reasoning: str = ""


class GeminiJudge:
    """
    Gemini-powered judge for hallucination detection and grounding verification.

    Uses Gemini 3's reasoning capabilities to:
    1. Semantically verify claims against evidence (not just ID matching)
    2. Detect subtle hallucinations that regex can't catch
    3. Explain why claims are/aren't supported
    4. Generate adversarial test cases
    """

    # System prompt for claim verification
    VERIFICATION_SYSTEM_PROMPT = """You are a rigorous fact-checker for a governance system.
Your job is to verify that claims in narrative memos are FULLY supported by the provided evidence.

CRITICAL RULES:
1. A claim is SUPPORTED only if the evidence DIRECTLY supports the specific assertion
2. A claim is UNSUPPORTED if:
   - It extrapolates beyond what evidence shows
   - It uses different numbers/values than evidence contains
   - It makes causal claims not established by evidence
   - It uses hedging language like "appears to", "likely", "probably"
   - It makes recommendations ("should", "recommend", "best")
   - It makes severity judgments ("critical", "urgent", "immediately")
   - It evaluates policy ("threshold is too", "policy should be")
3. Be strict. If in doubt, mark as UNSUPPORTED.

Output JSON in this exact format:
{
    "verifications": [
        {
            "claim_text": "...",
            "is_supported": true/false,
            "confidence": 0.0-1.0,
            "supporting_evidence_ids": ["id1", "id2"],
            "explanation": "Why supported/unsupported",
            "issues": ["Issue 1", "Issue 2"]
        }
    ],
    "overall_assessment": "Summary of memo quality",
    "passed": true/false
}"""

    # System prompt for adversarial generation
    ADVERSARIAL_SYSTEM_PROMPT = """You are a red-team tester for a governance system.
Your job is to generate test cases that might trick the hallucination detector.

Generate tricky test cases that:
1. Have subtle hallucinations (slightly wrong numbers, plausible but unsupported claims)
2. Use forbidden language in non-obvious ways ("this appears significant")
3. Reference evidence IDs that are close but not exact matches
4. Make claims that SOUND supported but aren't actually in evidence

For each test case, include:
- A memo with claims
- An evidence pack
- Whether it should pass or fail
- What error type it should trigger

Output JSON array of test cases."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "gemini-2.0-flash",
        strict_mode: bool = True,
        temperature: float = 0.1,
    ):
        """
        Initialize the Gemini judge.

        Args:
            api_key: Google API key (defaults to GOOGLE_API_KEY env var)
            model: Gemini model to use
            strict_mode: If True, any unsupported claim fails
            temperature: Lower = more consistent judgments
        """
        self.strict_mode = strict_mode
        self.temperature = temperature
        self.model = model

        # Initialize Gemini client
        if GeminiClient is None:
            raise ImportError("GeminiClient not available. Install google-genai package.")

        self._client = GeminiClient(api_key=api_key, model=model)

    def verify_claims(
        self,
        memo: Dict[str, Any],
        evidence_pack: Dict[str, Any],
    ) -> GeminiJudgeResult:
        """
        Verify all claims in a memo against evidence using Gemini.

        Args:
            memo: The narrative memo with claims
            evidence_pack: The evidence pack for verification

        Returns:
            GeminiJudgeResult with verification details
        """
        import time
        start_time = time.time()

        result = GeminiJudgeResult(passed=True)

        # Build the verification prompt
        prompt = self._build_verification_prompt(memo, evidence_pack)

        try:
            # Call Gemini
            response = self._client.generate(
                user_prompt=prompt,
                system_prompt=self.VERIFICATION_SYSTEM_PROMPT,
                temperature=self.temperature,
                max_tokens=4000,
            )

            # Parse response
            parsed = json.loads(response)

            # Process verifications
            verifications = parsed.get("verifications", [])
            for v in verifications:
                claim_v = ClaimVerification(
                    claim_text=v.get("claim_text", ""),
                    is_supported=v.get("is_supported", False),
                    confidence=v.get("confidence", 0.0),
                    supporting_evidence_ids=v.get("supporting_evidence_ids", []),
                    explanation=v.get("explanation", ""),
                    issues=v.get("issues", []),
                )
                result.claim_verifications.append(claim_v)
                result.total_claims += 1

                if claim_v.is_supported:
                    result.supported_claims += 1
                else:
                    result.unsupported_claims += 1
                    if self.strict_mode:
                        result.passed = False

            result.overall_explanation = parsed.get("overall_assessment", "")

            # Override passed if Gemini says so
            if not parsed.get("passed", True):
                result.passed = False

            # Calculate metrics
            if result.total_claims > 0:
                result.support_rate = result.supported_claims / result.total_claims
                confidences = [v.confidence for v in result.claim_verifications]
                result.average_confidence = sum(confidences) / len(confidences)

        except json.JSONDecodeError as e:
            result.errors.append(f"Failed to parse Gemini response: {e}")
            result.passed = False
        except Exception as e:
            result.errors.append(f"Gemini API error: {e}")
            result.passed = False

        result.latency_ms = (time.time() - start_time) * 1000
        return result

    def _build_verification_prompt(
        self,
        memo: Dict[str, Any],
        evidence_pack: Dict[str, Any],
    ) -> str:
        """Build the verification prompt."""
        # Extract claims from memo
        claims = []
        for section in memo.get("sections", []):
            for claim in section.get("claims", []):
                claims.append({
                    "text": claim.get("text", ""),
                    "section": section.get("heading", ""),
                    "cited_evidence_ids": [
                        ref.get("evidence_id")
                        for ref in claim.get("evidence_refs", [])
                    ],
                })

        # Format evidence
        evidence_items = evidence_pack.get("evidence_items", [])

        prompt = f"""Verify these claims against the evidence:

CLAIMS TO VERIFY:
{json.dumps(claims, indent=2)}

AVAILABLE EVIDENCE:
{json.dumps(evidence_items, indent=2)}

For each claim:
1. Check if the cited evidence IDs exist
2. Check if the claim is semantically supported by that evidence
3. Check for forbidden language patterns
4. Rate confidence 0.0-1.0

Return JSON with verifications array."""

        return prompt

    def generate_adversarial_cases(
        self,
        num_cases: int = 5,
        pack: str = "treasury",
    ) -> List[AdversarialTestCase]:
        """
        Generate adversarial test cases using Gemini.

        Args:
            num_cases: Number of test cases to generate
            pack: Domain pack (treasury/wealth) for context

        Returns:
            List of adversarial test cases
        """
        prompt = f"""Generate {num_cases} adversarial test cases for a {pack} governance memo.

Each test case should try to trick the hallucination detector in a different way:
1. Subtle number changes (evidence says $100M, claim says $105M)
2. Plausible but unsupported causal claims
3. Hedging language that sounds factual
4. References to evidence IDs that are close but wrong
5. Hidden recommendations ("a prudent approach would be...")

For {pack} pack, use realistic scenarios like:
- Position limit breaches
- Liquidity thresholds
- Counterparty exposure
- Settlement failures
- FX exposure

Output JSON array with {num_cases} test cases."""

        try:
            response = self._client.generate(
                user_prompt=prompt,
                system_prompt=self.ADVERSARIAL_SYSTEM_PROMPT,
                temperature=0.7,  # Higher for creativity
                max_tokens=8000,
            )

            parsed = json.loads(response)

            cases = []
            for i, case_data in enumerate(parsed if isinstance(parsed, list) else parsed.get("test_cases", [])):
                case = AdversarialTestCase(
                    id=f"adversarial_{pack}_{i+1:03d}",
                    name=case_data.get("name", f"Adversarial Case {i+1}"),
                    description=case_data.get("description", ""),
                    expected_result=case_data.get("expected_result", "fail"),
                    expected_error_type=case_data.get("expected_error_type"),
                    memo=case_data.get("memo", {}),
                    evidence_pack=case_data.get("evidence_pack", {}),
                    reasoning=case_data.get("reasoning", ""),
                )
                cases.append(case)

            return cases

        except Exception as e:
            # Return empty list on error
            return []

    def explain_failure(
        self,
        claim_text: str,
        evidence_items: List[Dict[str, Any]],
    ) -> str:
        """
        Get a detailed explanation of why a claim is unsupported.

        Args:
            claim_text: The claim that failed
            evidence_items: Available evidence

        Returns:
            Human-readable explanation
        """
        prompt = f"""Explain why this claim might be unsupported by the evidence.

CLAIM: {claim_text}

EVIDENCE: {json.dumps(evidence_items, indent=2)}

Provide:
1. What the claim asserts
2. What the evidence actually says
3. The gap between them
4. How to fix the claim

Be specific and educational."""

        try:
            response = self._client.generate(
                user_prompt=prompt,
                system_prompt="You are a helpful editor explaining evidence gaps.",
                temperature=0.3,
                max_tokens=1000,
            )
            return response
        except Exception:
            return "Unable to generate explanation."


def verify_with_gemini(
    memo: Dict[str, Any],
    evidence_pack: Dict[str, Any],
    strict: bool = True,
) -> GeminiJudgeResult:
    """
    Convenience function to verify a memo with Gemini.

    Args:
        memo: The narrative memo
        evidence_pack: The evidence pack
        strict: If True, any unsupported claim fails

    Returns:
        GeminiJudgeResult
    """
    judge = GeminiJudge(strict_mode=strict)
    return judge.verify_claims(memo, evidence_pack)
